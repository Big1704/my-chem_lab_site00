# 3. ประมวลผลและอัปเดตลงฐานข้อมูล
equipments = Equipment.objects.all()
updated_count = 0

for item in equipments:
    name_lower = item.name.lower()
    matched = False

    for info in GLASSWARE_DATA:
        if any(kw in name_lower for kw in info['keywords']):
            item.description = info['description']
            item.how_to_use = info['how_to_use']
            item.caution = info['caution']
            item.cleaning = info['cleaning']
            item.category = 'glassware'
            item.save()
            print(f'✅ อัปเดตสำเร็จ: {item.name}')
            matched = True
            updated_count += 1
            break

    if not matched:
        item.description = item.description or f'ใช้สำหรับปฏิบัติการทดลองทางเคมีเกี่ยวกับ {item.name}'
        item.how_to_use = item.how_to_use or f'ใช้งานตามขั้นตอนปฏิบัติการทดลองมาตรฐานสำหรับ {item.name}'
        item.caution = item.caution or 'ตรวจสอบรอยแตกร้าวหรือบิ่นก่อนใช้งานทุกครั้ง และสวมอุปกรณ์ป้องกันอันตราย'
        item.cleaning = item.cleaning or 'ล้างด้วยน้ำยาล้างจาน กลั้วด้วยน้ำกลั่น แล้วผึ่งให้แห้งสนิท'
        item.category = 'glassware'
        item.save()
        print(f'⚠️ เติมข้อมูลมาตรฐาน: {item.name}')
        updated_count += 1

print(f'\n🎉 เสร็จสิ้น! อัปเดตข้อมูลอุปกรณ์ไปทั้งหมด {updated_count} รายการเรียบร้อยแล้ว!')
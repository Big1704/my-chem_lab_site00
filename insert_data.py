def add_equipment_data():
    print("⏳ กำลังเริ่มเพิ่มข้อมูลอุปกรณ์และดาวน์โหลดรูปภาพ...")
    
    # URL สุ่มรูปภาพอุปกรณ์แก้ว/วิทยาศาสตร์
    image_url = "https://images.unsplash.com/photo-1532187863486-abf9dbad1b69?w=600&auto=format&fit=crop"

    for idx, item in enumerate(DATA, 1):
        obj, created = Equipment.objects.get_or_create(
            name=item["name"],
            defaults={
                "description": item["description"],
                "how_to_use": item["how_to_use"],
                "cleaning": item["cleaning"]
            }
        )
        
        # ดาวน์โหลดรูปภาพและใส่เข้าโมเดล (หากเป็นรายการใหม่ หรือยังไม่มีรูป)
        if created or not obj.image:
            try:
                response = requests.get(image_url, timeout=10)
                if response.status_code == 200:
                    filename = f"lab_item_{idx}.jpg"
                    obj.image.save(filename, ContentFile(response.content), save=True)
            except Exception as e:
                print(f"⚠️ ไม่สามารถดึงรูปภาพของ {item['name']} ได้: {e}")

        print(f"[{idx}/40] บันทึกสำเร็จ: {item['name']}")

    print("\n🎉 บันทึกข้อมูลและรูปภาพอุปกรณ์ทั้ง 40 รายการเรียบร้อยแล้ว!")

if __name__ == '__main__':
    add_equipment_data()